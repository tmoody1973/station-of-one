import json

import pytest

from station.config import load_prefs
from station.steps.page import page, render_front, render_story, story_path


def _newscast() -> dict:
    stories = [{"id": f"s{i}", "beat_id": "mke", "part": "lead" if i == 1 else "story", "headline": f"Story {i} headline",
                "summary": f"Summary {i}.", "score_matter_week": 0.62, "image": None, "seconds": 30,
                "chapter_start_ms": 9000 * i,
                "sources": [{"post_id": f"s{i}", "url": "https://ex.com/a", "author": "user7",
                             "source_name": "Urban Milwaukee", "posted_at": "2026-11-27T15:00:00Z"}]} for i in (1, 2)]
    return {"id": "2026-11-27T10", "hour_local": "2026-11-27T10:00:00-06:00", "show": "The Hourly Scroll",
            "station": "WONE", "frequency": "1.0 FM", "short": False,
            "counts": {"posts_read_hour": 5, "posts_read_today": 9, "posts_not_aired_today": 7, "stories_aired": 2},
            "stories": stories, "almost": [], "overheard": None,
            "chapters": [{"index": 0, "title": "Open", "kind": "open", "story_id": None, "start_ms": 0, "end_ms": 9000}],
            "audio": {"duration_ms": 60000, "bytes": 1, "key": "audio/2026-11-27T10-abcd1234.mp3"}, "voices_synthetic": True}


PHOTO = {"paragraphs": ["First paragraph.", "It is not yet clear."],
         "image": {"kind": "photo", "src": "https://ex.com/p.jpg", "credit": "Urban Milwaukee", "link": "https://ex.com/a"}}
ART = {"paragraphs": ["First paragraph."], "image": {"kind": "illustration", "src": "/art/2026-11-27T10-aa-bb.jpg"}}


def test_story_paths_unique():  # Review Focus 5
    a = story_path("2026-11-27T10", 0, "Same headline!")
    b = story_path("2026-11-27T10", 1, "Same headline!")
    assert a != b and a == "s/2026-11-27/1000/1-same-headline/index.html"
    assert story_path("2026-11-27T10", 2, "") == "s/2026-11-27/1000/3-story/index.html"
    assert story_path("2026-11-27T10", 3, "Kanal in former Citroën garage") == "s/2026-11-27/1000/4-kanal-in-former-citroen-garage/index.html"
    assert len(story_path("2026-11-27T10", 0, "word " * 40).split("/")[3]) <= 62  # "1-" + slug of at most 60


def test_story_page_has_article_sources_and_labels():
    n = _newscast()
    html = render_story(n, n["stories"][0], PHOTO, load_prefs())
    assert "First paragraph." in html and 'href="https://ex.com/a"' in html
    assert "likely to matter in a week" in html and "Voices are synthetic" in html
    assert '<meta property="og:image" content="https://ex.com/p.jpg">' in html
    assert 'src="/audio/2026-11-27T10-abcd1234.mp3"' in html and 'data-start-ms="9000"' in html
    assert "Story 2 headline" in html  # more from this hour


def test_illustration_is_labeled_and_absolute_in_og():
    n = _newscast()
    html = render_story(n, n["stories"][0], ART, load_prefs())
    assert "Illustration generated by machine for this story. Not a photograph." in html
    assert f'content="{load_prefs().hosting.public_base}/art/2026-11-27T10-aa-bb.jpg"' in html


def test_story_page_without_extras_falls_back_to_summary():
    n = _newscast()
    html = render_story(n, n["stories"][0], None, load_prefs())
    assert "Summary 1." in html and 'class="art"' in html and "not written this hour" in html


def test_untrusted_article_text_is_escaped():
    n = _newscast()
    html = render_story(n, n["stories"][0], {"paragraphs": ["<script>x</script>"], "image": None}, load_prefs())
    assert "&lt;script&gt;" in html and "<script>x" not in html


def test_front_links_story_pages_and_shows_story_image():
    n = _newscast()
    html = render_front(n, [n], load_prefs(), extras={"s1": PHOTO, "s2": ART})
    assert 'href="/s/2026-11-27/1000/1-story-1-headline/index.html"' in html
    assert 'href="/s/2026-11-27/1000/2-story-2-headline/index.html"' in html
    assert 'src="https://ex.com/p.jpg"' in html and 'src="/art/2026-11-27T10-aa-bb.jpg"' in html


def test_front_without_extras_has_no_story_links():
    n = _newscast()
    assert "/s/2026-11-27/" not in render_front(n, [n], load_prefs())


@pytest.fixture
def run_with_stories(tmp_path, monkeypatch):
    monkeypatch.setenv("STATION_TABLE", str(tmp_path / "table"))
    run = tmp_path / "runs" / "2026-11-27T10"
    run.mkdir(parents=True)
    (run / "newscast.json").write_text(json.dumps(_newscast()))
    (run / "stories.json").write_text(json.dumps({"s1": PHOTO, "s2": ART}))
    return run


def test_page_writes_story_pages_and_front_links_them(run_with_stories):
    written = page(run_with_stories, load_prefs(), runs_root=run_with_stories.parent, control_room=False)
    assert run_with_stories / "site/s/2026-11-27/1000/1-story-1-headline/index.html" in written
    assert 'href="/s/2026-11-27/1000/1-' in (run_with_stories / "site/index.html").read_text()
